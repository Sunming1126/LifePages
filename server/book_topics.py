def opening_questions(topic):
    title, first = topic['title'], topic['question']
    alternatives = OPENING_ALTERNATIVES.get(title, ())
    questions = list(dict.fromkeys((
        first, *alternatives,
        f'说到「{title}」，您最先想起谁？可以讲一件和对方有关的小事吗？',
        f'如果用一个具体画面来讲「{title}」，您会从哪里说起？',
        f'回想「{title}」，后来您对这段经历有什么新的体会？',
        f'关于「{title}」，您最想把哪一件事讲给家人听？',
    )))
    return questions[:4]
