"""Version 2 oral-history curriculum. IDs and published wording are immutable."""

from dataclasses import asdict, dataclass


@dataclass(frozen=True)
class Criterion:
    dimension: str
    sufficient: str
    clue_only: str
    probe: str
    not_applicable: str


@dataclass(frozen=True)
class Question:
    id: str
    prompt: str
    value: str
    applicability: str
    criteria: tuple[Criterion, ...]
    backup: str


@dataclass(frozen=True)
class Theme:
    id: str
    direction: str
    value: str
    core: tuple[str, str]
    questions: tuple[Question, ...]


DIMENSIONS = ('情境', '内容主体', '本人参与', '展开程度', '个人细节', '结果或意义')
CLUES = (
    '只说“小时候”“有个地方”，仍无法定位{target}，只是时间地点线索。',
    '只说“做过很多事”“一直这样”，没有讲出{target}，还没有可写的内容主体。',
    '只说“大家都这么做”，没有说明{target}，不能把他人的经历当作本人参与。',
    '只说“后来就好了”，没有展开{target}，仍缺可还原的过程或场景。',
    '只说“很好”“很辛苦”，没有呈现{target}，这些评价不能代替个人细节。',
    '只说“影响很大”，没有说明{target}，不能据此替用户写出感悟或后果。',
)
EXCEPTIONS = (
    '不要求准确年代、完整姓名或地址；大概阶段和人物关系足够。若从未有这类经历，换题。',
    '平常的小事也有价值，不要求重大事件；只有明确没有这类经历时才换入口。',
    '亲眼观察也可构成本人的经历，但须说明自己的视角；不强求用户必须是主角。',
    '日常可以没有转折；能展开一段动作、做法或生活场景即可，不强求戏剧性。',
    '不要求声音、气味、物品全部说齐；一两处贴合实际经历的真实细节即可。',
    '不强求人生感悟；已讲清实际收尾、日常状态或用户明确不愿谈意义时，可不适用。',
)


def question(tid, index, prompt, facts):
    """Each published question supplies six independently authored evidence targets."""
    targets = facts.split('；')
    assert len(targets) == 6, (tid, index, targets)
    criteria = tuple(Criterion(
        dimension, f'用户原话能具体说明{target}；允许大概时间、昵称和明确的不确定性。',
        CLUES[index].format(target=target),
        f'围绕“{target}”中尚未说清的一点，接住用户刚说的动作或场景，只问一个具体问题。',
        EXCEPTIONS[index]
    ) for index, (dimension, target) in enumerate(zip(DIMENSIONS, targets)))
    return Question(f'{tid}-q{index}', prompt, f'留下{targets[1]}，使这一人生片段可被后来的人理解。',
                    '只依据用户确认的经历；没有这类经历或不愿谈时换另一个入口，不预设学历、职业、婚姻或子女。',
                    criteria, f'可从“{targets[4]}”引导回忆，不列出未经确认的事实或替用户作答。')


def theme(number, title, value, core, rows):
    tid = f't{number:02d}'
    return Theme(tid, title, value, tuple(core.split('；')),
                 tuple(question(tid, i, prompt, facts) for i, (prompt, facts) in enumerate(rows, 1)))


